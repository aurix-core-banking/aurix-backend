CREATE INDEX idx_aml_alertas_cliente ON aurix.aml_alertas(cliente_id);
CREATE INDEX idx_aml_alertas_status ON aurix.aml_alertas(status);
CREATE INDEX idx_aml_alertas_score ON aurix.aml_alertas(score_risco DESC);


    data_criacao timestamp(6) not null,
    tenant_id varchar(64),
    versao integer not null,
    codigo_relatorio varchar(255) not null unique,
    tipo_relatorio varchar(50) not null,
    status varchar(50) not null,
    data_inicio_periodo timestamp(6) not null,
    data_fim_periodo timestamp(6) not null,
    data_geracao timestamp(6) not null,
    data_envio timestamp(6),
    total_notificacoes integer not null,
    total_transacoes_analisadas integer not null,
    resumo_estatistico JSONB,
    conteudo_relatorio TEXT,
    xml_relatorio TEXT,
    hash_relatorio varchar(100),
    observacoes TEXT,
    primary key (id)
);

-- ------------------------------------------------------------
-- PLD/AML - Prevencao a Lavagem de Dinheiro

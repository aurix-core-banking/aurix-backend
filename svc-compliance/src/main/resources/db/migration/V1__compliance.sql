-- ------------------------------------------------------------
-- COAF - Conselho de Controle de Atividades Financeiras
-- ------------------------------------------------------------
CREATE TABLE aurix.coaf_notificacoes (
    id bigint generated by default as identity,
    data_atualizacao timestamp(6),
    data_criacao timestamp(6) not null,
    tenant_id varchar(64),
    versao integer not null,
    codigo_notificacao varchar(255) not null unique,
    cliente_id bigint,
    cpf_cnpj varchar(14) not null,
    nome_cliente varchar(255) not null,
    tipo_notificacao varchar(50) not null,
    status varchar(50) not null,
    data_ocorrencia timestamp(6) not null,
    data_notificacao timestamp(6),
    prazo_notificacao timestamp(6) not null,
    motivo_suspeita varchar(255),
    descricao_operacao TEXT,
    valor_operacao numeric(18,2),
    moeda varchar(10) default 'BRL',
    tipo_operacao varchar(100),
    canal_operacao varchar(20),
    instituicao_origem varchar(200),
    instituicao_destino varchar(200),
    dados_transacao TEXT,
    xml_notificacao TEXT,
    observacoes TEXT,
    dentro_prazo boolean default true,
    dias_restantes integer,
    primary key (id)
);

CREATE INDEX idx_coaf_notificacoes_cliente ON aurix.coaf_notificacoes(cliente_id);
CREATE INDEX idx_coaf_notificacoes_status ON aurix.coaf_notificacoes(status);
CREATE INDEX idx_coaf_notificacoes_prazo ON aurix.coaf_notificacoes(prazo_notificacao);

CREATE TABLE aurix.coaf_relatorios (
    id bigint generated by default as identity,
